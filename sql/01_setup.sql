-- Idempotent staff acknowledgements: keep first acknowledged_at timestamp.
create or replace function public.sw_ack_task(p_task bigint,p_staff bigint)
returns void language plpgsql security definer set search_path=public,pg_temp as $$
begin
 if not exists(select 1 from public.sw_tasks where id=p_task) or
    not exists(select 1 from public.sw_staff where id=p_staff and active) then
  raise exception 'Staff or task not found' using errcode='P0001';
 end if;
 insert into public.sw_task_acks(task_id,staff_id)values(p_task,p_staff)on conflict do nothing;
 update public.sw_tasks set status='acknowledged' where id=p_task and status='new';
end $$;
revoke execute on function public.sw_ack_task(bigint,bigint) from public,anon,authenticated;
grant execute on function public.sw_ack_task(bigint,bigint) to service_role;

