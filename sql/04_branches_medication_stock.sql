create or replace function public.sw_available_at(p_date date,p_branch text)
returns table(key text,label_th text,label_en text,start text,"end" text,capacity int,used int,"left" int,closed boolean)
language sql stable set search_path=public,pg_temp as $$
 with window_counts as (
  select s.key,s.label_th,s.label_en,s.start_time,s.end_time,
   coalesce(br.closed,coalesce(o.closed,false) or extract(dow from p_date)::int = any (
    select jsonb_array_elements_text(coalesce((select value from public.sw_settings where key='closed_weekdays'),'[0]')::jsonb)::int
   )) as is_closed,
   coalesce(br.capacity,o.capacity,s.capacity) as cap,
   (select count(*)::int from public.sw_bookings b where b.date=p_date and b.slot_key=s.key
    and b.branch_id is not distinct from p_branch and b.status in ('pending','confirmed','checked_in')) as occupied
  from public.sw_slot_rules s left join public.sw_date_overrides o on o.date=p_date and o.slot_key=s.key
  left join public.sw_branch_date_slots br on br.branch_id=p_branch and br.date=p_date and br.slot_key=s.key
  where s.active and (p_branch is null or exists(select 1 from public.sw_clinic_locations where id=p_branch))
 )
 select x.key,x.label_th,x.label_en,to_char(x.start_time,'HH24:MI'),to_char(x.end_time,'HH24:MI'),
  case when x.is_closed then 0 else x.cap end,x.occupied,
  greatest(0,(case when x.is_closed then 0 else x.cap end)-x.occupied),x.is_closed
 from window_counts x order by x.start_time;
$$;

