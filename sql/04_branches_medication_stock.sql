returns public.sw_waitlist language sql set search_path=public,pg_temp as $$
 select public.sw_join_waitlist_at(p_customer,p_patient,p_date,p_slot,null);
$$;

create or replace function public.sw_accept_waitlist(p_customer bigint,p_waitlist bigint)
returns public.sw_bookings language plpgsql set search_path=public,pg_temp as $$
declare w public.sw_waitlist; b public.sw_bookings;
begin
 select * into w from public.sw_waitlist where id=p_waitlist and customer_id=p_customer for update;
 if not found then raise exception 'OFFER_NOT_AVAILABLE' using errcode='P0001'; end if;
 if w.status='booked' then select * into b from public.sw_bookings where id=w.booking_id; return b; end if;
 if w.status<>'offered' or w.offer_until<=now() then raise exception 'OFFER_NOT_AVAILABLE' using errcode='P0001'; end if;
 b:=public.sw_book_at_branch(p_customer,w.patient_id,w.date,w.slot_key,null,'','waitlist-'||w.id,w.branch_id,null,'waitlist');
 update public.sw_waitlist set status='booked',booking_id=b.id where id=w.id;
 return b;
end $$;

-- Count the first calendar day as day one. A partial last day is included.
-- One half unit is half of a tablet; the scheduler uses only a recorded regular regimen.
create or replace function public.sw_estimate_medication_depletion(p_start date,p_qty int,p_half int,p_times int)
returns date language sql immutable strict set search_path=public,pg_temp as $$
 select case when p_qty between 1 and 10000 and p_half between 1 and 40 and p_times between 1 and 8
  then p_start + ((2*p_qty+p_half*p_times-1)/(p_half*p_times))-1 end;
$$;

create or replace function public.sw_medication_inventory(p_branch text)
returns table(id bigint,name text,strength text,stock bigint,next_expiry date)
language sql stable set search_path=public,pg_temp as $$
 select d.id,d.name,d.strength,coalesce(sum(l.available_qty),0),min(l.expires_on)
 from public.sw_drug_catalog d left join public.sw_drug_lots l on l.drug_id=d.id and l.branch_id=p_branch
 and l.expires_on>=public.sw_thai_today() and l.available_qty>0
 where d.active group by d.id order by d.name,d.strength,d.id;
$$;

create or replace function public.sw_stock_medication(p_staff bigint,p_branch text,p_drug bigint,p_lot text,p_expiry date,p_qty int,p_request text default null)
returns public.sw_drug_lots language plpgsql set search_path=public,pg_temp as $$
declare lot public.sw_drug_lots; saved public.sw_drug_moves;
begin
 if not exists (select 1 from public.sw_staff where id=p_staff and active and clinical_access and role in ('owner','reception')) then
  raise exception 'CLINICAL_ACCESS_REQUIRED' using errcode='P0001';
 end if;
 if not exists(select 1 from public.sw_clinic_locations where id=p_branch) then raise exception 'BRANCH_REQUIRED' using errcode='P0001'; end if;
 if p_expiry is null or p_expiry<public.sw_thai_today() or p_qty is null or p_qty not between 1 and 100000 or
    p_lot is null or length(btrim(p_lot)) not between 1 and 60 then raise exception 'MED_STOCK_INVALID' using errcode='P0001'; end if;
 if p_request is not null then
  if length(p_request) not between 8 and 100 then raise exception 'REQUEST_INVALID' using errcode='P0001'; end if;
  perform pg_advisory_xact_lock(hashtextextended('sw:drug-intake:'||p_staff||':'||p_request,0));
  select * into saved from public.sw_drug_moves where request_id=p_request and staff_id=p_staff;
  if found then
   select * into lot from public.sw_drug_lots where id=saved.lot_id;
   if (lot.branch_id,lot.drug_id,lot.lot_no,lot.expires_on,saved.delta) is distinct from
    (p_branch,p_drug,upper(btrim(p_lot)),p_expiry,p_qty) then raise exception 'REQUEST_INVALID' using errcode='P0001'; end if;
   return lot;
  end if;
 end if;
 perform 1 from public.sw_drug_catalog where id=p_drug and active for update;
 if not found then raise exception 'MED_NOT_FOUND' using errcode='P0001'; end if;
 insert into public.sw_drug_lots(branch_id,drug_id,lot_no,expires_on,available_qty)
 values(p_branch,p_drug,upper(btrim(p_lot)),p_expiry,p_qty)
 on conflict(branch_id,drug_id,lot_no) do update set available_qty=sw_drug_lots.available_qty+excluded.available_qty
 where sw_drug_lots.expires_on=excluded.expires_on and sw_drug_lots.available_qty+excluded.available_qty<=1000000
 returning * into lot;
 if not found then raise exception 'MED_LOT_CONFLICT' using errcode='P0001'; end if;
 insert into public.sw_drug_moves(lot_id,delta,staff_id,request_id) values(lot.id,p_qty,p_staff,p_request);
 return lot;
end $$;

create or replace function public.sw_record_stock_dispense(
 p_staff bigint,p_booking bigint,p_patient bigint,p_branch text,p_ref text,p_items jsonb,p_request text,
 p_remind boolean,p_allow_refill boolean,p_refill_from date,p_refill_until date
) returns public.sw_dispenses language plpgsql set search_path=public,pg_temp as $$
declare b public.sw_bookings; d public.sw_dispenses; drug public.sw_drug_catalog; lot public.sw_drug_lots;
 item record; entry jsonb; entries jsonb:='[]'; due date; earliest date; opening date; ending date;
 clinic_day date:=public.sw_thai_today(); qty int; half int; times int; meal text; started date;
 drug_ids bigint[]:='{}'; remaining int; taken int;
 signature text:=encode(sha256(convert_to(jsonb_build_object(
  'ref',p_ref,'items',p_items,'remind',p_remind,'allow_refill',p_allow_refill,
  'from',p_refill_from,'until',p_refill_until)::text,'UTF8')),'hex');
begin
 if not exists (select 1 from public.sw_staff where id=p_staff and active and clinical_access and role in ('owner','reception')) then
  raise exception 'CLINICAL_ACCESS_REQUIRED' using errcode='P0001';
 end if;
 if coalesce(length(p_request),0) not between 8 and 100 then raise exception 'REQUEST_INVALID' using errcode='P0001'; end if;
 select * into b from public.sw_bookings where id=p_booking for update;
 if not found or b.patient_id is distinct from p_patient or b.status not in ('checked_in','completed') then
  raise exception 'VISIT_NOT_READY' using errcode='P0001';
 end if;
 if not exists (select 1 from public.sw_clinic_locations where id=p_branch) or
    (b.branch_id is not null and b.branch_id is distinct from p_branch) then raise exception 'MED_BRANCH_MISMATCH' using errcode='P0001'; end if;
 select * into d from public.sw_dispenses where booking_id=b.id;
 if found then
  if (d.patient_id,d.branch_id,d.recorded_by,d.record_request_id,d.record_request_hash) is not distinct from (p_patient,p_branch,p_staff,p_request,signature) then return d; end if;
  raise exception 'DISPENSE_ALREADY_RECORDED' using errcode='P0001';
 end if;
 if jsonb_typeof(p_items) is distinct from 'array' then raise exception 'DISPENSE_INVALID' using errcode='P0001'; end if;
 if jsonb_array_length(p_items) not between 1 and 30 then raise exception 'DISPENSE_INVALID' using errcode='P0001'; end if;
 for item in select j.value,j.ordinality from jsonb_array_elements(p_items) with ordinality j
 loop
  entry:=item.value;
  select * into drug from public.sw_drug_catalog where id=(entry->>'drug_id')::bigint and active;
  if not found then raise exception 'MED_NOT_FOUND' using errcode='P0001'; end if;
  if drug.id=any(drug_ids) then raise exception 'MED_DUPLICATE' using errcode='P0001'; end if;
  drug_ids:=array_append(drug_ids,drug.id);
  qty:=(entry->>'quantity')::int;
  half:=(entry->>'dose_half_units')::int;
  times:=(entry->>'times_daily')::int;
  meal:=entry->>'meal_timing';
  started:=(entry->>'started_on')::date;
  if qty is null or qty not between 1 and 10000 then raise exception 'DISPENSE_INVALID' using errcode='P0001'; end if;
  if (half is null)<>(times is null) or (half is null)<>(started is null) or
     (half is not null and (half not between 1 and 40 or times not between 1 and 8 or started<clinic_day or started>clinic_day+365 or
      2*qty<half or coalesce(meal,'') not in ('before_food','after_food','unspecified'))) then
   raise exception 'MED_SCHEDULE_INVALID' using errcode='P0001';
  end if;
  due:=public.sw_estimate_medication_depletion(started,qty,half,times);
  earliest:=least(earliest,due);
  entries:=entries||jsonb_build_array(jsonb_build_object(
   'position',item.ordinality,'drug_id',drug.id,'name',left(concat_ws(' ',drug.name,nullif(drug.strength,'')),150),
   'quantity',qty,'unit','tablet','directions',left(coalesce(entry->>'directions',''),300),
   'dose_half_units',half,'times_daily',times,'meal_timing',case when half is not null then meal end,'started_on',started,'depletion',due));
 end loop;
 if p_allow_refill then
  opening:=coalesce(p_refill_from,greatest(clinic_day,earliest-2));
  if earliest is null and p_refill_from is null then raise exception 'REFILL_WINDOW_INVALID' using errcode='P0001'; end if;
  ending:=p_refill_until;
  if opening is null or opening<clinic_day or ending is null or ending<opening then
   raise exception 'REFILL_WINDOW_INVALID' using errcode='P0001';
  end if;
 end if;
 d:=public.sw_record_dispense(p_staff,p_booking,p_patient,p_ref,entries,opening,ending);
 update public.sw_dispenses set branch_id=p_branch,record_request_id=p_request,record_request_hash=signature,estimated_depletion_on=earliest,
  remind_on=case when p_remind and earliest is not null then greatest(clinic_day,earliest-2) end
 where id=d.id returning * into d;
 for item in select * from jsonb_to_recordset(entries) as x(
  position int,drug_id bigint,quantity int,dose_half_units int,times_daily int,meal_timing text,started_on date,depletion date)
  order by drug_id
 loop
  perform 1 from public.sw_drug_catalog where id=item.drug_id and active for update;
  if not found then raise exception 'MED_NOT_FOUND' using errcode='P0001'; end if;
  update public.sw_dispense_items set drug_id=item.drug_id,dose_half_units=item.dose_half_units,
   times_daily=item.times_daily,meal_timing=item.meal_timing,started_on=item.started_on,estimated_depletion_on=item.depletion
  where dispense_id=d.id and position=item.position;
  remaining:=item.quantity;
  for lot in select l.* from public.sw_drug_lots l where l.drug_id=item.drug_id and l.branch_id=p_branch
   and l.expires_on>=clinic_day and l.available_qty>0 order by l.expires_on,l.id for update
  loop
   taken:=least(lot.available_qty,remaining);
   update public.sw_drug_lots set available_qty=available_qty-taken where id=lot.id;
   insert into public.sw_drug_moves(lot_id,delta,dispense_id,staff_id) values(lot.id,-taken,d.id,p_staff);
   remaining:=remaining-taken;
   exit when remaining=0;
  end loop;
  if remaining>0 then raise exception 'MED_STOCK_SHORT' using errcode='P0001'; end if;
 end loop;
 return d;
end $$;

create or replace function public.sw_stage_medication_reminders(p_now timestamptz default now(),p_dispense bigint default null)
returns integer language plpgsql set search_path=public,pg_temp as $$
declare clock timestamp:=p_now at time zone 'Asia/Bangkok'; affected int;
begin
 if clock::time<time '07:00' then return 0; end if;
 insert into public.sw_notifications(event_type,destination,to_id,payload,event_key,deadline)
 select 'medication_depletion','customer',c.line_user_id,
  jsonb_build_object('clinic_v3',true,'lang',c.preferred_lang,'dispense_id',d.id,
   'depletion_on',d.estimated_depletion_on,
   'can_refill',coalesce(clock::date between d.refill_from and d.refill_until,false)),
  'medication:depletion:'||d.id,(d.estimated_depletion_on+1)::timestamp at time zone 'Asia/Bangkok'
 from public.sw_dispenses d join public.sw_patients p on p.id=d.patient_id
 join public.sw_customers c on c.id=p.customer_id
 where (p_dispense is null or d.id=p_dispense) and d.remind_on<=clock::date and d.estimated_depletion_on>=clock::date and c.line_user_id<>''
 and not exists(select 1 from public.sw_refill_requests r where r.dispense_id=d.id and r.status<>'withdrawn')
 on conflict(event_key) do nothing;
 get diagnostics affected=row_count;
 return affected;
end $$;

create or replace function public.sw_clinic_tick()
returns jsonb language plpgsql set search_path=public,pg_temp as $$
declare w record; reminders integer; medication_reminders integer; offers integer:=0;
begin
 reminders:=public.sw_stage_clinic_reminders();
 medication_reminders:=public.sw_stage_medication_reminders();
 delete from public.sw_patient_qr where expires_at<now();
 update public.sw_waitlist set status='expired' where date<public.sw_thai_today() and status in ('waiting','offered');
 for w in select q.date,q.slot_key,q.branch_id from public.sw_waitlist q
  where q.status in ('waiting','offered') and q.date>=public.sw_thai_today()
  group by q.date,q.slot_key,q.branch_id order by q.date,q.slot_key,q.branch_id limit 200 loop
  if (public.sw_offer_waitlist_at(w.date,w.slot_key,w.branch_id)).id is not null then offers:=offers+1; end if;
 end loop;
 return jsonb_build_object('reminders',reminders,'medication_reminders',medication_reminders,'offers',offers);
end $$;

