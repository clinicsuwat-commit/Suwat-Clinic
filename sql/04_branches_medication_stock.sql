create or replace function public.sw_assign_booking_branch(p_staff bigint,p_booking bigint,p_branch text)
returns public.sw_bookings language plpgsql set search_path=public,pg_temp as $$
declare b public.sw_bookings; a record;
begin
 if not exists (select 1 from public.sw_staff where id=p_staff and active and role in ('owner','reception')) then
  raise exception 'STAFF_REQUIRED' using errcode='P0001';
 end if;
 if not exists(select 1 from public.sw_clinic_locations where id=p_branch) then raise exception 'BRANCH_REQUIRED' using errcode='P0001'; end if;
 select * into b from public.sw_bookings where id=p_booking for update;
 if not found then raise exception 'VISIT_NOT_READY' using errcode='P0001'; end if;
 if b.branch_id=p_branch then return b; end if;
 if b.branch_id is not null then raise exception 'BRANCH_ALREADY_ASSIGNED' using errcode='P0001'; end if;
 if b.date<public.sw_thai_today() or b.status not in ('pending','confirmed','checked_in') then
  raise exception 'VISIT_NOT_READY' using errcode='P0001';
 end if;
 perform 1 from public.sw_slot_rules where key=b.slot_key and active for update;
 perform pg_advisory_xact_lock(hashtextextended(b.date::text||':'||b.slot_key||':'||p_branch,0));
 select * into a from public.sw_available_at(b.date,p_branch) where key=b.slot_key;
 if not found or a.closed then raise exception 'SLOT_CLOSED' using errcode='P0001'; end if;
 if a."left"<1 then raise exception 'SLOT_FULL' using errcode='P0001'; end if;
 update public.sw_bookings set branch_id=p_branch,updated_at=now() where id=b.id returning * into b;
 update public.sw_reschedule set desired_branch=p_branch where booking_id=b.id and desired_branch is null and status='pending';
 return b;
end $$;


create or replace function public.sw_booking_guard()
returns trigger language plpgsql set search_path=public,pg_temp as $$
begin
 if tg_op='UPDATE' then
  if (new.date,new.slot_key,new.appointment_time,new.branch_id) is distinct from (old.date,old.slot_key,old.appointment_time,old.branch_id) then
   new.appointment_revision:=old.appointment_revision+1;
   new.attending_at:=null;
  end if;
  if (new.customer_id,new.patient_id,new.date) is not distinct from (old.customer_id,old.patient_id,old.date)
     and old.status in ('pending','confirmed','checked_in')
     and not (old.status='pending' and new.status='confirmed') then
   return new;
  end if;
 end if;
 if new.status in ('pending','confirmed','checked_in') then
  perform pg_advisory_xact_lock(hashtextextended('sw:customer:'||new.customer_id||':'||new.date,0));
  if exists (select 1 from public.sw_same_day_bookings(new.customer_id,new.patient_id,new.date,new.patient_name,new.id)) then
   raise exception 'BOOKING_DUPLICATE' using errcode='P0001';
  end if;
 end if;
 return new;
end $$;

create or replace function public.sw_visit_payload(p_booking public.sw_bookings)
returns jsonb language sql stable set search_path=public,pg_temp as $$
 select jsonb_build_object(
  'booking_id',p_booking.id,'revision',p_booking.appointment_revision,
  'ref',p_booking.booking_ref,'date',p_booking.date,
  'from',to_char(coalesce(p_booking.appointment_time,s.start_time),'HH24:MI'),
  'until',case when p_booking.appointment_time is null then to_char(s.end_time,'HH24:MI') else null end)||public.sw_location_content(p_booking.branch_id)
 from public.sw_slot_rules s where s.key=p_booking.slot_key;
$$;

create or replace function public.sw_book_at_branch(
 p_customer bigint,p_patient bigint,p_date date,p_slot text,p_time time,p_symptoms text,p_request text,p_branch text,
 p_staff bigint default null,p_source text default 'online'
) returns public.sw_bookings language plpgsql set search_path=public,pg_temp as $$
declare pt public.sw_patients; c public.sw_customers; slot public.sw_slot_rules;
 b public.sw_bookings; a record; clinic_now timestamp; v_mode text;
begin
 if p_branch is not null and not exists (select 1 from public.sw_clinic_locations where id=p_branch) then
  raise exception 'BRANCH_REQUIRED' using errcode='P0001'; end if;
 select * into pt from public.sw_patients where id=p_patient and customer_id=p_customer;
 if not found then raise exception 'PATIENT_NOT_FOUND' using errcode='P0001'; end if;
 select * into c from public.sw_customers where id=p_customer;
 if c.phone !~ '^0[0-9]{9}$' then raise exception 'PHONE_REQUIRED' using errcode='P0001'; end if;
 if p_staff is not null and not exists(select 1 from public.sw_staff where id=p_staff and active and role in ('owner','reception')) then
  raise exception 'STAFF_REQUIRED' using errcode='P0001';
 end if;
 if p_staff is not null and pt.hn is null then raise exception 'HN_REQUIRED' using errcode='P0001'; end if;
 clinic_now:=now() at time zone 'Asia/Bangkok';
 if p_date is null or p_date<clinic_now::date or p_date>clinic_now::date+90 then raise exception 'BOOKING_DATE_INVALID' using errcode='P0001'; end if;
 if coalesce(char_length(p_request),0) not between 8 and 100 then raise exception 'REQUEST_INVALID' using errcode='P0001'; end if;
 perform pg_advisory_xact_lock(hashtextextended('sw:request:'||p_customer||':'||p_request,0));
 select * into b from public.sw_bookings where customer_id=p_customer and request_id=p_request;
 if found then
  if (b.patient_id,b.date,b.slot_key,b.appointment_time,b.created_by,b.branch_id) is distinct from (p_patient,p_date,p_slot,p_time,p_staff,p_branch) then
   raise exception 'REQUEST_INVALID' using errcode='P0001';
  end if;
  return b;
 end if;
 select * into slot from public.sw_slot_rules where key=p_slot and active for update;
 if not found or (p_time is not null and (p_time<slot.start_time or p_time>=slot.end_time)) then
  raise exception 'BOOKING_TIME_INVALID' using errcode='P0001';
 end if;
 if p_date+coalesce(p_time,slot.end_time)<=clinic_now then raise exception 'BOOKING_TIME_INVALID' using errcode='P0001'; end if;
 if exists (select 1 from public.sw_same_day_bookings(p_customer,p_patient,p_date,pt.full_name)) then
  raise exception 'BOOKING_DUPLICATE' using errcode='P0001';
 end if;
 perform pg_advisory_xact_lock(hashtextextended(p_date::text||':'||p_slot||coalesce(':'||p_branch,''),0));
 select * into a from public.sw_available_at(p_date,p_branch) where key=p_slot;
 if not found or a.closed then raise exception 'SLOT_CLOSED' using errcode='P0001'; end if;
 if a."left"<1 then raise exception 'SLOT_FULL' using errcode='P0001'; end if;
 select value into v_mode from public.sw_settings where key='booking_mode';
 insert into public.sw_bookings(booking_ref,customer_id,patient_id,patient_name,patient_phone,date,slot_key,
  appointment_time,symptoms,status,request_id,source,created_by,branch_id)
 values('SWC-'||to_char(clinic_now,'YYMMDD')||'-'||upper(substr(replace(gen_random_uuid()::text,'-',''),1,12)),
  p_customer,p_patient,pt.full_name,c.phone,p_date,p_slot,p_time,left(coalesce(p_symptoms,''),500),
  case when p_staff is not null or (v_mode='auto' and c.phone_verified) then 'confirmed' else 'pending' end,p_request,p_source,p_staff,p_branch)
 returning * into b;
 if p_staff is null then
  insert into public.sw_tasks(kind,reference_id,title) values('booking',b.id,'New appointment '||b.booking_ref);
  perform public.sw_clinic_notify_staff('booking:staff:'||b.id,'staff_booking',false);
 end if;
 return b;
end $$;

