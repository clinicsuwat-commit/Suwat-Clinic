create or replace function public.sw_thai_today() returns date
language sql stable set search_path=public,pg_temp as $$
 select (now() at time zone 'Asia/Bangkok')::date;
$$;

create or replace function public.sw_same_day_bookings(p_customer bigint,p_patient bigint,p_date date,p_name text,p_skip bigint default null)
returns setof public.sw_bookings language sql stable set search_path=public,pg_temp as $$
 select b.* from public.sw_bookings b
 where b.customer_id=p_customer and b.date=p_date and b.status in ('pending','confirmed','checked_in')
 and (p_skip is null or b.id<>p_skip)
 and ((p_patient is not null and b.patient_id=p_patient)
 or ((p_patient is null or b.patient_id is null) and lower(regexp_replace(btrim(b.patient_name),'[[:space:]]+',' ','g')) =
     lower(regexp_replace(btrim(p_name),'[[:space:]]+',' ','g'))));
$$;

create or replace function public.sw_booking_guard()
returns trigger language plpgsql set search_path=public,pg_temp as $$
begin
 if tg_op='UPDATE' then
  if (new.date,new.slot_key,new.appointment_time) is distinct from (old.date,old.slot_key,old.appointment_time) then
   new.appointment_revision:=old.appointment_revision+1;
   new.attending_at:=null;
  end if;
  if (new.customer_id,new.patient_id,new.date) is not distinct from (old.customer_id,old.patient_id,old.date)
     and old.status in ('pending','confirmed','checked_in')
     and not (old.status='pending' and new.status='confirmed') then
   return new;
  end if;
 end if;
 if new.status in ('pending','confirmed','checked_in') then
  perform pg_advisory_xact_lock(hashtextextended('sw:customer:'||new.customer_id||':'||new.date,0));
  if exists (select 1 from public.sw_same_day_bookings(new.customer_id,new.patient_id,new.date,new.patient_name,new.id)) then
   raise exception 'BOOKING_DUPLICATE' using errcode='P0001';
  end if;
 end if;
 return new;
end $$;
drop trigger if exists sw_booking_guard on public.sw_bookings;
create trigger sw_booking_guard before insert or update on public.sw_bookings
for each row execute function public.sw_booking_guard();

create or replace function public.sw_clinic_queue(
 p_key text,p_kind text,p_destination text,p_to text,p_lang text,p_data jsonb,
 p_deadline timestamptz default null
) returns void language sql set search_path=public,pg_temp as $$
 insert into public.sw_notifications(event_type,destination,to_id,payload,event_key,deadline)
 select p_kind,p_destination,p_to,jsonb_build_object('clinic_v3',true,'lang',p_lang)||coalesce(p_data,'{}'),p_key,p_deadline
 where p_to is not null and p_to<>''
 on conflict(event_key) do nothing;
$$;

create or replace function public.sw_clinic_notify_staff(p_key text,p_kind text,p_clinical boolean)
returns void language sql set search_path=public,pg_temp as $$
 insert into public.sw_notifications(event_type,destination,to_id,payload,event_key,deadline)
 select p_kind,'staff',s.line_user_id,'{"clinic_v3":true,"lang":"th"}'::jsonb,p_key||':'||s.id,now()+interval '1 day'
 from public.sw_staff s
 where s.active and s.role in ('owner','reception') and s.line_user_id is not null
 and (not p_clinical or s.clinical_access)
 on conflict(event_key) do nothing;
$$;

create or replace function public.sw_visit_payload(p_booking public.sw_bookings)
returns jsonb language sql stable set search_path=public,pg_temp as $$
 select jsonb_build_object(
  'booking_id',p_booking.id,'revision',p_booking.appointment_revision,
  'ref',p_booking.booking_ref,'date',p_booking.date,
  'from',to_char(coalesce(p_booking.appointment_time,s.start_time),'HH24:MI'),
  'until',case when p_booking.appointment_time is null then to_char(s.end_time,'HH24:MI') else null end)
 from public.sw_slot_rules s where s.key=p_booking.slot_key;
$$;

create or replace function public.sw_visit_notifications()
returns trigger language plpgsql set search_path=public,pg_temp as $$
declare v_kind text; c public.sw_customers;
begin
 if tg_op='INSERT' then
  v_kind:=case when new.status='confirmed' then 'visit_confirmed' else 'visit_requested' end;
 elsif new.status='cancelled' and old.status<>new.status then
  v_kind:='visit_cancelled';
  update public.sw_reschedule set status='withdrawn',closed_at=now() where booking_id=new.id and status='pending';
 elsif new.appointment_revision<>old.appointment_revision then v_kind:='visit_updated';
 elsif new.status='confirmed' and old.status='pending' then v_kind:='visit_confirmed';
 end if;
 if v_kind is not null then
  select * into c from public.sw_customers where id=new.customer_id;
  perform public.sw_clinic_queue('visit:'||new.id||':'||new.appointment_revision||':'||v_kind,
   v_kind,'customer',c.line_user_id,c.preferred_lang,public.sw_visit_payload(new),now()+interval '1 day');
 end if;
 return new;
end $$;
drop trigger if exists sw_visit_notifications on public.sw_bookings;
create trigger sw_visit_notifications after insert or update on public.sw_bookings
for each row execute function public.sw_visit_notifications();

create or replace function public.sw_book_patient(
 p_customer bigint,p_patient bigint,p_date date,p_slot text,p_time time,p_symptoms text,p_request text,
 p_staff bigint default null,p_source text default 'online'
) returns public.sw_bookings language plpgsql set search_path=public,pg_temp as $$
declare pt public.sw_patients; c public.sw_customers; slot public.sw_slot_rules;
 b public.sw_bookings; a record; clinic_now timestamp; v_mode text;
begin
 select * into pt from public.sw_patients where id=p_patient and customer_id=p_customer;
 if not found then raise exception 'PATIENT_NOT_FOUND' using errcode='P0001'; end if;
 select * into c from public.sw_customers where id=p_customer;
 if c.phone !~ '^0[0-9]{9}$' then raise exception 'PHONE_REQUIRED' using errcode='P0001'; end if;
 if p_staff is not null and not exists(select 1 from public.sw_staff where id=p_staff and active and role in ('owner','reception')) then
  raise exception 'STAFF_REQUIRED' using errcode='P0001';
 end if;
 if p_staff is not null and pt.hn is null then raise exception 'HN_REQUIRED' using errcode='P0001'; end if;
 clinic_now:=now() at time zone 'Asia/Bangkok';
 if p_date is null or p_date<clinic_now::date or p_date>clinic_now::date+90 then raise exception 'BOOKING_DATE_INVALID' using errcode='P0001'; end if;
 if coalesce(char_length(p_request),0) not between 8 and 100 then raise exception 'REQUEST_INVALID' using errcode='P0001'; end if;
 perform pg_advisory_xact_lock(hashtextextended('sw:request:'||p_customer||':'||p_request,0));
 select * into b from public.sw_bookings where customer_id=p_customer and request_id=p_request;
 if found then
  if (b.patient_id,b.date,b.slot_key,b.appointment_time,b.created_by) is distinct from (p_patient,p_date,p_slot,p_time,p_staff) then
   raise exception 'REQUEST_INVALID' using errcode='P0001';
  end if;
  return b;
 end if;
 select * into slot from public.sw_slot_rules where key=p_slot and active for update;
 if not found or (p_time is not null and (p_time<slot.start_time or p_time>=slot.end_time)) then
  raise exception 'BOOKING_TIME_INVALID' using errcode='P0001';
 end if;
 if p_date+coalesce(p_time,slot.end_time)<=clinic_now then raise exception 'BOOKING_TIME_INVALID' using errcode='P0001'; end if;
 if exists (select 1 from public.sw_same_day_bookings(p_customer,p_patient,p_date,pt.full_name)) then
  raise exception 'BOOKING_DUPLICATE' using errcode='P0001';
 end if;
 perform pg_advisory_xact_lock(hashtextextended(p_date::text||':'||p_slot,0));
 select * into a from public.sw_available(p_date) where key=p_slot;
 if not found or a.closed then raise exception 'SLOT_CLOSED' using errcode='P0001'; end if;
 if a."left"<1 then raise exception 'SLOT_FULL' using errcode='P0001'; end if;
 select value into v_mode from public.sw_settings where key='booking_mode';
 insert into public.sw_bookings(booking_ref,customer_id,patient_id,patient_name,patient_phone,date,slot_key,
  appointment_time,symptoms,status,request_id,source,created_by)
 values('SWC-'||to_char(clinic_now,'YYMMDD')||'-'||upper(substr(replace(gen_random_uuid()::text,'-',''),1,12)),
  p_customer,p_patient,pt.full_name,c.phone,p_date,p_slot,p_time,left(coalesce(p_symptoms,''),500),
  case when p_staff is not null or (v_mode='auto' and c.phone_verified) then 'confirmed' else 'pending' end,p_request,p_source,p_staff)
 returning * into b;
 if p_staff is null then
  insert into public.sw_tasks(kind,reference_id,title) values('booking',b.id,'New appointment '||b.booking_ref);
  perform public.sw_clinic_notify_staff('booking:staff:'||b.id,'staff_booking',false);
 end if;
 return b;
end $$;

create or replace function public.sw_link_hn(p_patient bigint,p_hn text,p_staff bigint)
returns public.sw_patients language plpgsql set search_path=public,pg_temp as $$
declare pt public.sw_patients;
begin
 if not exists(select 1 from public.sw_staff where id=p_staff and active and role in ('owner','reception')) then
  raise exception 'STAFF_REQUIRED' using errcode='P0001';
 end if;
 select * into pt from public.sw_patients where id=p_patient for update;
 if not found then raise exception 'PATIENT_NOT_FOUND' using errcode='P0001'; end if;
 if pt.hn=p_hn then return pt; end if;
 if pt.hn is not null then raise exception 'HN_ALREADY_LINKED' using errcode='P0001'; end if;
 update public.sw_patients set hn=p_hn,hn_linked_at=now(),hn_linked_by=p_staff where id=p_patient returning * into pt;
 return pt;
exception when unique_violation then raise exception 'HN_IN_USE' using errcode='P0001';
end $$;

create or replace function public.sw_claim_visit(p_booking bigint,p_patient bigint,p_staff bigint)
returns public.sw_bookings language plpgsql set search_path=public,pg_temp as $$
declare b public.sw_bookings; pt public.sw_patients;
begin
 if not exists(select 1 from public.sw_staff where id=p_staff and active and role in ('owner','reception'))
  then raise exception 'STAFF_REQUIRED' using errcode='P0001'; end if;
 select * into pt from public.sw_patients where id=p_patient and hn is not null;
 if not found then raise exception 'HN_REQUIRED' using errcode='P0001'; end if;
 select * into b from public.sw_bookings where id=p_booking for update;
 if not found or b.customer_id<>pt.customer_id or (b.patient_id is not null and b.patient_id<>pt.id) then
  raise exception 'VISIT_PATIENT_MISMATCH' using errcode='P0001';
 end if;
 if b.patient_id is null and lower(regexp_replace(btrim(b.patient_name),'[[:space:]]+',' ','g')) <>
     lower(regexp_replace(btrim(pt.full_name),'[[:space:]]+',' ','g')) then
  raise exception 'VISIT_PATIENT_MISMATCH' using errcode='P0001';
 end if;
 if b.date<>public.sw_thai_today() or b.status not in ('confirmed','checked_in','completed') then raise exception 'VISIT_NOT_READY' using errcode='P0001'; end if;
 update public.sw_bookings set patient_id=pt.id,status=case when b.status='completed' then 'completed' else 'checked_in' end,updated_at=now() where id=p_booking returning * into b;
 return b;
end $$;

create or replace function public.sw_request_reschedule(p_booking bigint,p_customer bigint,p_date date,p_slot text)
returns public.sw_reschedule language plpgsql set search_path=public,pg_temp as $$
declare b public.sw_bookings; r public.sw_reschedule;
begin
 select * into b from public.sw_bookings where id=p_booking and customer_id=p_customer for update;
 if not found or b.status not in ('pending','confirmed') or b.date<public.sw_thai_today() then
  raise exception 'VISIT_NOT_READY' using errcode='P0001';
 end if;
 if p_date is null or p_date<public.sw_thai_today() or p_date>public.sw_thai_today()+90 or
    (b.date,b.slot_key)=(p_date,p_slot) or not exists (
     select 1 from public.sw_available(p_date) a where a.key=p_slot and not a.closed and a."left">0
      and p_date+(a."end"::time)>(now() at time zone 'Asia/Bangkok')
    ) then raise exception 'RESCHEDULE_SLOT_INVALID' using errcode='P0001'; end if;
 select * into r from public.sw_reschedule where booking_id=p_booking and status='pending';
 if found then raise exception 'RESCHEDULE_ALREADY_PENDING' using errcode='P0001'; end if;
 insert into public.sw_reschedule(booking_id,desired_date,desired_slot) values(p_booking,p_date,p_slot) returning * into r;
 perform public.sw_clinic_notify_staff('reschedule:staff:'||r.id,'staff_reschedule',false);
 return r;
end $$;

create or replace function public.sw_decide_reschedule(p_request bigint,p_staff bigint,p_accept boolean)
returns public.sw_bookings language plpgsql set search_path=public,pg_temp as $$
declare r public.sw_reschedule; b public.sw_bookings; s public.sw_slot_rules; c public.sw_customers; a record;
begin
 if not exists(select 1 from public.sw_staff where id=p_staff and active and role in ('owner','reception')) then
  raise exception 'STAFF_REQUIRED' using errcode='P0001';
 end if;
 select * into r from public.sw_reschedule where id=p_request;
 if not found then raise exception 'RESCHEDULE_NOT_FOUND' using errcode='P0001'; end if;
 select * into b from public.sw_bookings where id=r.booking_id for update;
 select * into r from public.sw_reschedule where id=p_request for update;
 if r.status<>'pending' or b.status not in ('pending','confirmed') or b.date<public.sw_thai_today() then
  raise exception 'VISIT_NOT_READY' using errcode='P0001';
 end if;
 if p_accept then
  select * into s from public.sw_slot_rules where key=r.desired_slot and active for update;
  if not found or r.desired_date+s.end_time<=(now() at time zone 'Asia/Bangkok') then
   raise exception 'RESCHEDULE_SLOT_INVALID' using errcode='P0001';
  end if;
  perform pg_advisory_xact_lock(hashtextextended(r.desired_date::text||':'||r.desired_slot,0));
  select * into a from public.sw_available(r.desired_date) where key=r.desired_slot;
  if not found or a."left"<1 then raise exception 'SLOT_FULL' using errcode='P0001'; end if;
  update public.sw_bookings set date=r.desired_date,slot_key=r.desired_slot,appointment_time=null,updated_at=now() where id=b.id returning * into b;
 else
  select * into c from public.sw_customers where id=b.customer_id;
  perform public.sw_clinic_queue('reschedule:declined:'||r.id,'reschedule_declined','customer',c.line_user_id,c.preferred_lang,public.sw_visit_payload(b),now()+interval '1 day');
 end if;
 update public.sw_reschedule set status=case when p_accept then 'accepted' else 'declined' end,closed_at=now(),closed_by=p_staff where id=r.id;
 return b;
end $$;

create or replace function public.sw_offer_waitlist(p_date date,p_slot text)
returns public.sw_waitlist language plpgsql set search_path=public,pg_temp as $$
declare w public.sw_waitlist; c public.sw_customers; a record; deadline timestamptz;
begin
 perform pg_advisory_xact_lock(hashtextextended('sw:waitlist:'||p_date||':'||p_slot,0));
 select * into a from public.sw_available(p_date) where key=p_slot;
 if not found then return null; end if;
 update public.sw_waitlist set status='expired' where date=p_date and slot_key=p_slot and
  ((status='offered' and offer_until<=now()) or (status='waiting' and p_date+(a.start::time)<=(now() at time zone 'Asia/Bangkok')));
 if a."left"<1 or exists(select 1 from public.sw_waitlist where date=p_date and slot_key=p_slot and status='offered') then return null; end if;
 deadline:=least(now()+interval '2 hours',(p_date+(a.start::time)) at time zone 'Asia/Bangkok');
 if deadline<=now() then return null; end if;
 select q.* into w from public.sw_waitlist q join public.sw_patients pt on pt.id=q.patient_id
 where q.date=p_date and q.slot_key=p_slot and q.status='waiting'
 and not exists(select 1 from public.sw_same_day_bookings(q.customer_id,q.patient_id,q.date,pt.full_name))
 order by q.id limit 1 for update of q skip locked;
 if not found then return null; end if;
 update public.sw_waitlist set status='offered',offer_until=deadline where id=w.id returning * into w;
 select * into c from public.sw_customers where id=w.customer_id;
 perform public.sw_clinic_queue('waitlist:'||w.id,'waitlist_offer','customer',c.line_user_id,c.preferred_lang,
  jsonb_build_object('waitlist_id',w.id,'date',w.date,'from',a.start,'until',a."end",'offer_until',deadline),deadline);
 return w;
end $$;

create or replace function public.sw_join_waitlist(p_customer bigint,p_patient bigint,p_date date,p_slot text)
returns public.sw_waitlist language plpgsql set search_path=public,pg_temp as $$
declare pt public.sw_patients; a record; w public.sw_waitlist;
begin
 select * into pt from public.sw_patients where customer_id=p_customer and id=p_patient;
 if not found then raise exception 'PATIENT_NOT_FOUND' using errcode='P0001'; end if;
 if not exists(select 1 from public.sw_customers where id=p_customer and phone ~ '^0[0-9]{9}$')
  then raise exception 'PHONE_REQUIRED' using errcode='P0001'; end if;
 if p_date is null or p_date<public.sw_thai_today() or p_date>public.sw_thai_today()+90 then
  raise exception 'BOOKING_DATE_INVALID' using errcode='P0001';
 end if;
 select * into a from public.sw_available(p_date) where key=p_slot;
 if not found or a.closed or p_date+(a.start::time)<=(now() at time zone 'Asia/Bangkok') then
  raise exception 'SLOT_CLOSED' using errcode='P0001';
 end if;
 if exists(select 1 from public.sw_same_day_bookings(p_customer,p_patient,p_date,pt.full_name)) then
  raise exception 'BOOKING_DUPLICATE' using errcode='P0001';
 end if;
 if a."left">0 then raise exception 'SLOT_ALREADY_OPEN' using errcode='P0001'; end if;
 insert into public.sw_waitlist(customer_id,patient_id,date,slot_key) values(p_customer,p_patient,p_date,p_slot)
 on conflict (patient_id,date,slot_key) where status in ('waiting','offered') do nothing returning * into w;
 if w.id is null then select * into w from public.sw_waitlist where patient_id=p_patient and date=p_date and slot_key=p_slot and status in ('waiting','offered'); end if;
 return w;
end $$;

create or replace function public.sw_accept_waitlist(p_customer bigint,p_waitlist bigint)
returns public.sw_bookings language plpgsql set search_path=public,pg_temp as $$
declare w public.sw_waitlist; b public.sw_bookings;
begin
 select * into w from public.sw_waitlist where id=p_waitlist and customer_id=p_customer for update;
 if not found then raise exception 'OFFER_NOT_AVAILABLE' using errcode='P0001'; end if;
 if w.status='booked' then select * into b from public.sw_bookings where id=w.booking_id; return b; end if;
 if w.status<>'offered' or w.offer_until<=now() then raise exception 'OFFER_NOT_AVAILABLE' using errcode='P0001'; end if;
 b:=public.sw_book_patient(p_customer,w.patient_id,w.date,w.slot_key,null,'','waitlist-'||w.id,null,'waitlist');
 update public.sw_waitlist set status='booked',booking_id=b.id where id=w.id;
 return b;
end $$;

create or replace function public.sw_record_dispense(
 p_staff bigint,p_booking bigint,p_patient bigint,p_ref text,p_items jsonb,p_from date,p_until date
) returns public.sw_dispenses language plpgsql set search_path=public,pg_temp as $$
declare b public.sw_bookings; d public.sw_dispenses; item record;
begin
 if not exists (select 1 from public.sw_staff where id=p_staff and active and clinical_access and role in ('owner','reception')) then
  raise exception 'CLINICAL_ACCESS_REQUIRED' using errcode='P0001';
 end if;
 select * into b from public.sw_bookings where id=p_booking for update;
 if not found or b.patient_id is distinct from p_patient or b.status not in ('checked_in','completed') or
    not exists(select 1 from public.sw_patients where id=p_patient and hn is not null) then raise exception 'VISIT_NOT_READY' using errcode='P0001'; end if;
 if exists(select 1 from public.sw_dispenses where booking_id=b.id) then raise exception 'DISPENSE_ALREADY_RECORDED' using errcode='P0001'; end if;
 if p_ref is null or char_length(p_ref) not between 1 and 100 or jsonb_typeof(p_items) is distinct from 'array' or
    jsonb_array_length(p_items) not between 1 and 30 then raise exception 'DISPENSE_INVALID' using errcode='P0001'; end if;
 if (p_from is null)<>(p_until is null) or (p_from is not null and (p_from<public.sw_thai_today() or p_until<p_from)) then
  raise exception 'REFILL_WINDOW_INVALID' using errcode='P0001';
 end if;
 insert into public.sw_dispenses(booking_id,patient_id,prescription_ref,recorded_by,refill_from,refill_until)
 values(b.id,p_patient,p_ref,p_staff,p_from,p_until) returning * into d;
 insert into public.sw_dispense_items(dispense_id,position,name,quantity,unit,directions)
 select d.id,x.ordinality,btrim(x.value->>'name'),(x.value->>'quantity')::integer,btrim(x.value->>'unit'),coalesce(x.value->>'directions','')
 from jsonb_array_elements(p_items) with ordinality as x(value,ordinality);
 return d;
end $$;

create or replace function public.sw_request_refill(
 p_customer bigint,p_dispense bigint,p_recipient text,p_phone text,p_address text,p_postal text,p_request text
) returns public.sw_refill_requests language plpgsql set search_path=public,pg_temp as $$
declare d public.sw_dispenses; pt public.sw_patients; r public.sw_refill_requests; c public.sw_customers;
begin
 if coalesce(char_length(p_request),0) not between 8 and 100 then raise exception 'REQUEST_INVALID' using errcode='P0001'; end if;
 select d0.* into d from public.sw_dispenses d0 join public.sw_patients p on p.id=d0.patient_id
 where d0.id=p_dispense and p.customer_id=p_customer and p.hn is not null for update of d0;
 if not found then raise exception 'REFILL_NOT_AVAILABLE' using errcode='P0001'; end if;
 select * into r from public.sw_refill_requests where customer_id=p_customer and request_id=p_request;
 if found then
  if (r.dispense_id,r.recipient,r.shipping_phone,r.shipping_address,r.postal_code) is distinct from
     (p_dispense,p_recipient,p_phone,p_address,p_postal) then raise exception 'REQUEST_INVALID' using errcode='P0001'; end if;
  return r;
 end if;
 if d.refill_from is null or public.sw_thai_today() not between d.refill_from and d.refill_until then
  raise exception 'REFILL_NOT_AVAILABLE' using errcode='P0001';
 end if;
 if exists (select 1 from public.sw_refill_requests where dispense_id=d.id and status='pending') then
  raise exception 'REFILL_ALREADY_PENDING' using errcode='P0001';
 end if;
 select * into pt from public.sw_patients where id=d.patient_id;
 select * into c from public.sw_customers where id=p_customer;
 insert into public.sw_refill_requests(dispense_id,patient_id,customer_id,recipient,shipping_phone,shipping_address,postal_code,request_id)
 values(d.id,pt.id,p_customer,p_recipient,p_phone,p_address,p_postal,p_request) returning * into r;
 perform public.sw_clinic_queue('refill:customer:'||r.id,'refill_received','customer',c.line_user_id,c.preferred_lang,jsonb_build_object('ref',r.ref));
 perform public.sw_clinic_notify_staff('refill:staff:'||r.id,'staff_refill',true);
 return r;
end $$;

create or replace function public.sw_review_refill(p_staff bigint,p_request bigint,p_status text)
returns public.sw_refill_requests language plpgsql set search_path=public,pg_temp as $$
declare r public.sw_refill_requests; c public.sw_customers;
begin
 if not exists(select 1 from public.sw_staff where id=p_staff and active and clinical_access and role in ('owner','reception')) then
  raise exception 'CLINICAL_ACCESS_REQUIRED' using errcode='P0001';
 end if;
 if p_status not in ('contacted','visit_required','declined') or p_status is null then raise exception 'STATUS_INVALID' using errcode='P0001'; end if;
 update public.sw_refill_requests set status=p_status,reviewed_at=now(),reviewed_by=p_staff
 where id=p_request and status='pending' returning * into r;
 if not found then raise exception 'REFILL_NOT_PENDING' using errcode='P0001'; end if;
 select * into c from public.sw_customers where id=r.customer_id;
 perform public.sw_clinic_queue('refill:review:'||r.id,'refill_reviewed','customer',c.line_user_id,c.preferred_lang,jsonb_build_object('ref',r.ref,'status',r.status));
 return r;
end $$;

create or replace function public.sw_stage_clinic_reminders(p_now timestamptz default now())
returns integer language plpgsql set search_path=public,pg_temp as $$
declare clinic_now timestamp:=p_now at time zone 'Asia/Bangkok'; affected integer;
begin
 if clinic_now::time<time '07:00' then return 0; end if;
 insert into public.sw_notifications(event_type,destination,to_id,payload,event_key,deadline)
 select case when b.date=clinic_now::date then 'reminder_today' else 'reminder_tomorrow' end,'customer',c.line_user_id,
  jsonb_build_object('clinic_v3',true,'lang',c.preferred_lang)||public.sw_visit_payload(b),
  'reminder:'||b.id||':'||b.appointment_revision||':'||(b.date-clinic_now::date),
  (case when b.date=clinic_now::date then b.date+coalesce(b.appointment_time,s.start_time) else b.date::timestamp end)
    at time zone 'Asia/Bangkok'
 from public.sw_bookings b join public.sw_customers c on c.id=b.customer_id join public.sw_slot_rules s on s.key=b.slot_key
 where b.status='confirmed' and b.date between clinic_now::date and clinic_now::date+1 and c.line_user_id<>''
 and (b.date>clinic_now::date or b.date+coalesce(b.appointment_time,s.start_time)>clinic_now)
 on conflict(event_key) do nothing;
 get diagnostics affected=row_count;
 return affected;
end $$;

create or replace function public.sw_clinic_tick()
returns jsonb language plpgsql set search_path=public,pg_temp as $$
declare w record; reminders integer; offers integer:=0;
begin
 reminders:=public.sw_stage_clinic_reminders();
 delete from public.sw_patient_qr where expires_at<now();
 update public.sw_waitlist set status='expired' where date<public.sw_thai_today() and status in ('waiting','offered');
 for w in select q.date,q.slot_key from public.sw_waitlist q where q.status in ('waiting','offered') and q.date>=public.sw_thai_today()
  group by q.date,q.slot_key order by q.date,q.slot_key limit 200 loop
  if (public.sw_offer_waitlist(w.date,w.slot_key)).id is not null then offers:=offers+1; end if;
 end loop;
 return jsonb_build_object('reminders',reminders,'offers',offers);
end $$;

create or replace function public.sw_claim_notifications(p_limit int default 8)
returns setof public.sw_notifications language plpgsql security definer set search_path=public,pg_temp as $$
begin
 update public.sw_notifications set status='failed',last_error='Expired or replaced',locked_at=null
 where (status='pending' or (status='processing' and locked_at<now()-interval '3 minutes'))
 and (deadline<=now() or attempts>=5 or
      (event_type in ('reminder_today','reminder_tomorrow','visit_confirmed','visit_updated','visit_requested')
       and payload ? 'clinic_v3' and not exists (
        select 1 from public.sw_bookings b where b.id::text=payload->>'booking_id'
        and b.appointment_revision::text=payload->>'revision'
        and (b.status=case when event_type='visit_requested' then 'pending' else 'confirmed' end
         or (event_type='visit_updated' and b.status='pending'))
       ))
      or (event_type='waitlist_offer' and not exists(
       select 1 from public.sw_waitlist w where w.id::text=payload->>'waitlist_id'
       and w.status='offered' and w.offer_until>now()
      )));
 return query with selected as (
  select n.id from public.sw_notifications n
  where (n.status='pending' or (n.status='processing' and n.locked_at<now()-interval '3 minutes'))
  and n.attempts<5 and n.available_at<=now() and (n.deadline is null or n.deadline>now())
  order by n.deadline asc nulls last,n.id limit least(greatest(p_limit,1),20) for update skip locked
 ) update public.sw_notifications n set status='processing',locked_at=now(),attempts=n.attempts+1
 from selected where n.id=selected.id returning n.*;
end $$;

-- Limit all new records and RPCs to the server. No browser key reads HR or clinical data.
do $$
declare t text; f regprocedure;
begin
 foreach t in array array['sw_patients','sw_patient_qr','sw_reschedule','sw_waitlist','sw_dispenses','sw_dispense_items','sw_refill_requests'] loop
  execute format('alter table public.%I enable row level security',t);
  execute format('revoke all on public.%I from public,anon,authenticated',t);
  execute format('grant select,insert,update,delete on public.%I to service_role',t);
  if t not in ('sw_patient_qr','sw_dispense_items') then
   execute format('grant usage,select on sequence %s to service_role',pg_get_serial_sequence('public.'||t,'id'));
  end if;
 end loop;
 for f in select p.oid::regprocedure from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public'
  and p.proname=any(array['sw_thai_today','sw_same_day_bookings','sw_booking_guard','sw_clinic_queue','sw_clinic_notify_staff','sw_visit_payload',
   'sw_visit_notifications','sw_book_patient','sw_link_hn','sw_claim_visit','sw_request_reschedule','sw_decide_reschedule','sw_offer_waitlist',
   'sw_join_waitlist','sw_accept_waitlist','sw_record_dispense','sw_request_refill','sw_review_refill','sw_stage_clinic_reminders','sw_clinic_tick','sw_claim_notifications']) loop
  execute format('revoke all on function %s from public,anon,authenticated',f);
  execute format('grant execute on function %s to service_role',f);
 end loop;
end $$;
notify pgrst, 'reload schema';
commit;
